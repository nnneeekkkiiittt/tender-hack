const FALLBACK_ANSWER =
  'Спасибо за вопрос! Уточните, пожалуйста, о какой именно закупке, документе или разделе Портала идёт речь — так я смогу дать более точный ответ. Если нужна помощь специалиста, вы можете создать обращение в поддержку.'

export class DemoAiService implements AiService {
  async ask(question: string): Promise<AskResult> {
    await wait(700)
    const q = question.toLowerCase()
    const match = KNOWLEDGE_BASE.find((entry) => entry.keywords.some((kw) => q.includes(kw)))
    if (match) {
      return { answer: match.answer, sources: match.sources }
    }
    return { answer: FALLBACK_ANSWER, sources: [] }
  }
}
